def _build_axaml_resource_dictionary(lang_code: str, strings: Dict[str, str]) -> str:
    lines = [
        '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
        '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml"',
        '                    xmlns:sys="clr-namespace:System;assembly=System.Runtime">',
        f'    <!-- Neoveg i18n Resource Dictionary: {lang_code} ({strings.get("Meta.NativeName", lang_code)}) -->',
    ]
    for key, val in sorted(strings.items()):
        escaped_val = saxutils.escape(val, {'"': "&quot;", "'": "&apos;"})
        lines.append(f'    <sys:String x:Key="{key}">{escaped_val}</sys:String>')
    lines.append("</ResourceDictionary>")
    return "\n".join(lines) + "\n"


